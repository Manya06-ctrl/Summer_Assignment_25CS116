// square pattern with increasing number
#include <stdio.h>
int main(){
    int n;
    int num=1;
    printf("enter the number n:");
    scanf("%d",&n);
    for(int i=1;i<=n;i++){
        
        for(int j=1;j<=n;j++){
            printf("num");
            num++;
        }
        printf("\n");

    }
    return 0;
}
